/**
 * Drive DRISHTI-G with months of plausible municipal traffic.
 *
 *   npm run sim:run -- --days 180 --per-day 30 --seed 42
 *
 * Why this is not a database seeder
 * ---------------------------------
 * The system's interesting behaviour is not in its tables, it is in what the
 * engines do when work arrives: GCCE reads the text and picks a department, the
 * priority engine scores urgency, the clustering engine notices that eleven
 * people reported the same choked drain, the scheduler escalates what nobody
 * touched, GRIE scores the units that keep missing deadlines. A seeder that
 * writes rows produces a database that *looks* like all of that happened and a
 * system that has never actually done any of it.
 *
 * So every action here goes through the real HTTP API, as the real actor, with
 * a real session cookie. A synthetic citizen registers and files; the officer
 * GCCE actually chose logs in and issues a work order; a crew member opens the
 * code with no account at all and reports the job done; the officer inspects
 * it. Nothing is written on their behalf. If routing is broken, this run fails
 * the way a user would experience it being broken.
 *
 * The one exception, stated plainly
 * ---------------------------------
 * Timestamps. The API stamps `now()` on everything, and six months of work that
 * all happened this afternoon is useless for a log whose whole purpose is
 * elapsed time. After the API has finished with a case, `lib/sim-clock.ts`
 * rewrites its timestamps onto the simulated schedule. **Every row's existence
 * and content is real; its timestamp is fiction.** That module is env-gated and
 * refuses to run in production; see its header for the reasoning.
 *
 * What this data may and may not be used for
 * ------------------------------------------
 * It may train the in-system classifier, predictor and SLA estimator, fill the
 * screens, and demonstrate the engines running. It is **not evidence for any
 * claim in either paper** — it is generated by the same system it would be used
 * to evaluate, which is circular. See docs/pending-work.md and
 * docs/research-decisions.md.
 */
