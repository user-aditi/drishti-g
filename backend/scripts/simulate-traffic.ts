interface Options {
  days: number
  perDay: number
  breachRate: number
  overrideRate: number
  seed: number
  baseUrl: string
  citizens: number
  password: string
  /** Clear the previous simulation before running, so the seed reproduces. */
  reset: boolean
}

/** Synthetic residents are recognisable by address, and nothing else is. */
const SIM_EMAIL_PREFIX = 'sim.'
const SIM_EMAIL_DOMAIN = '@residents.example'

function parseOptions(argv: string[]): Options {
  const flags = new Map<string, string>()
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i]!
    if (!token.startsWith('--')) continue
    const [name, inline] = token.slice(2).split('=')

    if (inline !== undefined) {
      flags.set(name!, inline)
      continue
    }

    // A valueless flag must not swallow the one after it. `--reset --days 5`
    // consumed `--days` as reset's value in the first version, so `days` fell
    // back to its default of 180 and a five-day smoke test quietly filed 1,626
    // complaints. Only take the next token if it is not itself a flag.
    const next = argv[i + 1]
    if (next !== undefined && !next.startsWith('--')) {
      flags.set(name!, next)
      i++
    } else {
      flags.set(name!, '')
    }
  }

  const number = (name: string, fallback: number): number => {
    const raw = flags.get(name)
    if (raw === undefined) return fallback
    const value = Number(raw)
    if (!Number.isFinite(value)) throw new Error(`--${name} must be a number, got ${raw}`)
    return value
  }

  return {
    days: number('days', 180),
    perDay: number('per-day', 30),
    breachRate: number('breach-rate', 0.15),
    overrideRate: number('override-rate', 0.1),
    seed: number('seed', 20260909),
    citizens: number('citizens', 120),
    baseUrl: flags.get('base-url') ?? 'http://localhost:4000/api/v1',
    password: flags.get('password') ?? 'drishti123',
    reset: flags.has('reset'),
  }
}

