/**
 * Bring the synthetic residents online, registering them the first time.
 *
 * Addresses are derived from the seed, not from the clock, so the same seed
 * addresses the same people every run. An account that already exists is signed
 * into rather than recreated — accounts are never deleted between runs, because
 * deleting a user nulls `AuditEvent.actorId` and breaks the hash chain for
 * everything they ever did.
 */
async function registerCitizens(
  options: Options,
  rng: Rng,
  units: { id: number; isLeaf: boolean }[],
): Promise<Session[]> {
  const leaves = units.filter((u) => u.isLeaf)
  const homes = leaves.length > 0 ? leaves : units
  const sessions: Session[] = []
  let reused = 0

  for (let i = 0; i < options.citizens; i++) {
    const fullName = `${rng.pick(FIRST)} ${rng.pick(LAST)}`
    const email = `${SIM_EMAIL_PREFIX}${options.seed}.${i}${SIM_EMAIL_DOMAIN}`
    const session = new Session(options.baseUrl, fullName)

    try {
      await session.post('/auth/register', {
        email,
        password: options.password,
        fullName,
        homeUnitId: homes.length > 0 ? rng.pick(homes).id : null,
      })
      sessions.push(session)
    } catch (error) {
      if (!(error instanceof ApiError) || error.status !== 409) throw error
      // Already exists from an earlier run — sign in instead.
      try {
        await session.post('/auth/login', { email, password: options.password })
        sessions.push(session)
        reused++
      } catch {
        // An account at this address exists with a different password; skip it.
      }
    }
  }

  if (sessions.length === 0) throw new Error('Could not bring any synthetic residents online.')
  if (reused > 0) console.log(`  (${reused} of them already existed and were signed in)`)
  return sessions
}

async function officerSession(officer: Officer, options: Options): Promise<Session | null> {
  if (officer.session) return officer.session
  const session = new Session(options.baseUrl, officer.fullName)
  try {
    await session.post('/auth/login', { email: officer.email, password: options.password })
  } catch {
    // A seeded officer whose password differs from the demo one simply cannot
    // act; their complaints stay unallotted, which is a realistic vacancy.
    return null
  }
  officer.session = session
  return session
}

