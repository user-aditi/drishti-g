interface Officer {
  id: number
  email: string
  fullName: string
  session?: Session
}

interface CrewMember {
  id: number
  /** The API nests it; flattened on the way in so the filter below reads plainly. */
  sector: { id: number } | null
}

interface Catalogue {
  units: { id: number; name: string; isLeaf: boolean }[]
  officers: Map<number, Officer>
  crewByOfficer: Map<number, CrewMember[]>
}

/**
 * Read the authority through the console, as a Super Admin would.
 *
 * Deliberately not read from Prisma: if the console cannot describe the
 * authority, the simulator should fail here rather than quietly produce traffic
 * against a shape the API disagrees with.
 */
async function loadCatalogue(admin: Session): Promise<Catalogue> {
  const staff = await admin.get<{
    items: { id: number; email: string; fullName: string; rank: string }[]
  }>('/console/staff?size=100&rank=SECTION_OFFICER')

  const officers = new Map<number, Officer>()
  for (const person of staff.items) {
    if (person.rank === 'SECTION_OFFICER') {
      officers.set(person.id, { id: person.id, email: person.email, fullName: person.fullName })
    }
  }

  return { units: await walkTree(admin), officers, crewByOfficer: new Map() }
}

/**
 * Flatten the org tree by walking it from the root.
 *
 * There is no flat-list endpoint — the console drills down one unit at a time,
 * which is right for the screen and awkward here. Walking it is a handful of
 * requests against a tree twenty-odd units wide, and it keeps the simulator
 * reading the authority through the same API everything else uses.
 */
async function walkTree(admin: Session): Promise<Catalogue['units']> {
  const { rootId } = await admin.get<{ rootId: number }>('/console/units')
  const units: Catalogue['units'] = []
  const queue = [rootId]
  const seen = new Set<number>()

  while (queue.length > 0) {
    const id = queue.shift()!
    if (seen.has(id)) continue
    seen.add(id)

    const detail = await admin.get<{
      unit: { id: number; name: string; isLeaf: boolean }
      children: { id: number; name: string; isLeaf: boolean }[]
    }>(`/console/units/${id}`)

    units.push(detail.unit)
    for (const child of detail.children ?? []) queue.push(child.id)
  }

  return units
}

